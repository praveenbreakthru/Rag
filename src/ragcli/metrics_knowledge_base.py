def lookup_metric_by_query(query: str) -> Optional[MetricDefinition]:
    """Matches a user query string against metric IDs, names, and aliases."""
    import re
    q_clean = query.lower().strip()

    # 1. Direct ID word match (e.g. 'ebitda', 'pat', 'pbt', 'crar', 'roe', 'roa')
    for m_id, m in METRICS_CATALOGUE.items():
        if re.search(r"\b" + re.escape(m_id.lower()) + r"\b", q_clean):
            return m

    # 2. Metric name substring match
    for m in METRICS_CATALOGUE.values():
        clean_name = re.sub(r"\(.*?\)", "", m.metric_name).lower().strip()
        if clean_name and clean_name in q_clean:
            return m

    # 3. Exact alias match
    for m in METRICS_CATALOGUE.values():
        for alias in m.aliases:
            if re.search(r"\b" + re.escape(alias.lower()) + r"\b", q_clean):
                return m

    return None
